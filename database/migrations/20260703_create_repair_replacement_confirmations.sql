CREATE TABLE IF NOT EXISTS repair_replacement_confirmations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  store_id BIGINT UNSIGNED NOT NULL,
  repair_order_id BIGINT UNSIGNED NOT NULL,
  source_key VARCHAR(190) NOT NULL,
  product_id BIGINT UNSIGNED NULL,
  sku VARCHAR(80) NULL,
  item_name VARCHAR(255) NOT NULL,
  quantity DECIMAL(12,2) NOT NULL DEFAULT 1,
  unit_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  note TEXT NULL,
  is_replaced TINYINT(1) NOT NULL DEFAULT 0,
  is_tested TINYINT(1) NOT NULL DEFAULT 0,
  is_stock_handled TINYINT(1) NOT NULL DEFAULT 0,
  is_photo_confirmed TINYINT(1) NOT NULL DEFAULT 0,
  checked_by_staff_id BIGINT UNSIGNED NULL,
  checked_by_staff_name VARCHAR(120) NULL,
  checked_at DATETIME NULL,
  cross_checked_by_staff_id BIGINT UNSIGNED NULL,
  cross_checked_by_staff_name VARCHAR(120) NULL,
  cross_checked_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uniq_repair_replacement_source (store_id, repair_order_id, source_key),
  INDEX idx_repair_replacement_repair (store_id, repair_order_id, id),
  INDEX idx_repair_replacement_cross_check (store_id, repair_order_id, cross_checked_at)
);
